// 三才五行组合粗略吉凶提示
function sanCai(shen, ren, di) {
  const wx = (n) => ({ 1: '木', 2: '木', 3: '火', 4: '火', 5: '土', 6: '土', 7: '金', 8: '金', 9: '水', 0: '水' })[n % 10];
  return { tian: wx(shen), ren: wx(ren), di: wx(di) };
}

export function calcName({ surname, given }) {
  const chars = (surname + given).split('');
  const unknown = chars.filter((c) => strokes(c) === null);
  const s1 = strokes(surname[0]);
  const s2 = surname.length > 1 ? strokes(surname[1]) : null;
  const g1 = strokes(given[0]);
  const g2 = given.length > 1 ? strokes(given[1]) : null;
  const isSingleGiven = given.length === 1;

  const tian = surname.length > 1 ? s1 + s2 : s1 + 1;
  const ren = (s2 ?? s1) + g1;
  const di = isSingleGiven ? g1 + 1 : g1 + g2;
  const total = (s1 + (s2 ?? 0) + g1 + (g2 ?? 0));
  const wai = total - ren + 1;

  const li = (n) => {
    const v = n > 81 ? n - 81 : n;
    const info = SHU_LI[v];
    return info ? { num: v, ji: info[0], desc: info[1] } : { num: v, ji: '未知', desc: '' };
  };

  return {
    surname,
    given,
    fullName: surname + given,
    strokes: { s1, s2, g1, g2, unknown },
    ge: {
      天格: { num: tian, ...li(tian) },
      人格: { num: ren, ...li(ren) },
      地格: { num: di, ...li(di) },
      外格: { num: wai, ...li(wai) },
      总格: { num: total, ...li(total) },
    },
    sanCai: sanCai(tian, ren, di),
  };
}

